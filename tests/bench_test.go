func TestBench_AuditHTML_Hermetic(t *testing.T) {
	html := `<!DOCTYPE html>
<html>
<head>
  <style>body { color: #333; }</style>
  <template type="text/inert-script">console.log("inert");</template>
</head>
<body>
  <h1>Hermetic Page</h1>
  <img src="data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII=">
</body>
</html>`

	leaks, score := bench.AuditHTML(html)
	if len(leaks) != 0 {
		t.Fatalf("expected 0 leaks, got %d: %+v", len(leaks), leaks)
	}
	if score != 100.0 {
		t.Fatalf("expected 100.0 hermetic score, got %.1f", score)
	}
}

func TestBench_AuditHTML_DetectsLeaks(t *testing.T) {
	leakyHTML := `<!DOCTYPE html>
<html>
<head>
  <script src="https://cdn.example.com/lib.js"></script>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css?family=Roboto">
</head>
<body>
  <img src="https://tracking.com/pixel.gif">
  <iframe src="https://embed.remote.com/frame"></iframe>
</body>
</html>`

	leaks, score := bench.AuditHTML(leakyHTML)
	if len(leaks) != 4 {
		t.Fatalf("expected 4 detected leaks, got %d", len(leaks))
	}
	if score > 20.0 {
		t.Fatalf("expected severe score drop for multiple critical leaks, got %.1f", score)
	}

	foundScript := false
	foundStyle := false
	foundImg := false
	foundIframe := false

	for _, l := range leaks {
		switch l.ElementType {
		case "<script>":
			foundScript = true
			if l.Severity != bench.SeverityCritical {
				t.Fatalf("expected critical severity for remote script, got %s", l.Severity)
			}
		case "<link rel=stylesheet>":
			foundStyle = true
		case "<img>":
			foundImg = true
			if l.Severity != bench.SeverityWarn {
				t.Fatalf("expected warn severity for remote image, got %s", l.Severity)
			}
		case "<iframe>":
			foundIframe = true
		}
	}

	if !foundScript || !foundStyle || !foundImg || !foundIframe {
		t.Fatalf("did not detect all leak types: script=%v style=%v img=%v iframe=%v",
			foundScript, foundStyle, foundImg, foundIframe)
	}
}

func TestBench_ValidateWARC_ValidAndInvalid(t *testing.T) {
	// Test empty / truncated data
	invalid := bench.ValidateWARC([]byte("bad"))
	if invalid.ValidFormat {
		t.Fatalf("expected invalid format on 3-byte payload")
	}

	// Test valid WARC stream generated by demo
	suite := bench.GenerateDemoSuite()
	if len(suite.CorpusResults) == 0 {
		t.Fatalf("suite generated zero corpuses")
	}

	res := suite.CorpusResults[0]
	if !res.ISOReport.ValidFormat {
		t.Fatalf("expected valid ISO format on first demo corpus")
	}
	if !res.ISOReport.HasWarcInfo {
		t.Fatalf("expected warcinfo record")
	}
	if !res.ISOReport.HasResponse {
		t.Fatalf("expected response record")
	}
	if res.ISOReport.RecordCount < 2 {
		t.Fatalf("expected >= 2 records, got %d", res.ISOReport.RecordCount)
	}
}

func TestBench_EvaluateArchival_HighFidelity(t *testing.T) {
	engine := bench.NewEngine()

	rawHTML := `<!DOCTYPE html><html><head><title>Test</title></head><body><p>Hello</p></body></html>`
	bundledHTML := rawHTML

	snap := &archive.Snapshot{
		ID:          "snap_eval_1",
		URL:         "https://example.com/test",
		Title:       "Test",
		Timestamp:   time.Now(),
		WaybackTS:   "20261018120000",
		HTML:        bundledHTML,
		ContentType: "text/html; charset=utf-8",
		StatusCode:  200,
		SizeBytes:   int64(len(bundledHTML)),
	}

	res, err := engine.EvaluateSnapshot(snap)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if !res.Passed {
		t.Fatalf("expected clean snapshot to pass benchmark, got: %s", res.Summary)
	}
	if res.FidelityScore < 85.0 {
		t.Fatalf("expected fidelity score >= 85.0, got %.1f", res.FidelityScore)
	}
	if res.Metrics.SerializationLatencyUs <= 0 {
		t.Fatalf("expected positive serialization latency")
	}
}

func TestBench_SuiteExecution(t *testing.T) {
	suite := bench.GenerateDemoSuite()
	if !suite.OverallPassed {
		t.Fatalf("expected demo suite to pass overall, got failed suite: %+v", suite)
	}
	if suite.PassedCount != 3 {
		t.Fatalf("expected exactly 3 passing corpuses (with 1 caught leak breach), got %d", suite.PassedCount)
	}
	if suite.MeanFidelity < 75.0 {
		t.Fatalf("expected mean fidelity >= 75.0%%, got %.1f%%", suite.MeanFidelity)
	}

	// Verify hostile trap was flagged
	leakCorpus := suite.CorpusResults[2]
	if leakCorpus.Status != bench.StatusLeakDetected {
		t.Fatalf("expected leak trap corpus to be flagged LEAK_DETECTED, got %s", leakCorpus.Status)
	}
	if len(leakCorpus.Leaks) != 2 {
		t.Fatalf("expected 2 leaks in trap, got %d", len(leakCorpus.Leaks))
	}
}

func TestBench_ScorecardAndMarkdownRendering(t *testing.T) {
	suite := bench.GenerateDemoSuite()

	ansi := bench.RenderSuiteScorecard(suite)
	if !strings.Contains(ansi, "TIMECAPSULE ARCHIVAL FIDELITY") {
		t.Fatalf("missing header in ANSI scorecard: %s", ansi)
	}
	if !strings.Contains(ansi, "LEAK BREACH") {
		t.Fatalf("missing LEAK BREACH badge in scorecard: %s", ansi)
	}

	md := bench.RenderMarkdown(suite)
	if !strings.Contains(md, "TimeCapsule Archival Fidelity & ISO 28500 Benchmark") {
		t.Fatalf("missing markdown header: %s", md)
	}
	if !strings.Contains(md, "Hermetic Score") {
		t.Fatalf("missing Hermetic Score column in markdown: %s", md)
	}

	jsonStr, err := bench.RenderJSON(suite)
	if err != nil {
		t.Fatalf("failed to render JSON: %v", err)
	}
	if !strings.Contains(jsonStr, "\"fidelity_score\"") {
		t.Fatalf("missing fidelity_score in JSON: %s", jsonStr)
	}
}
